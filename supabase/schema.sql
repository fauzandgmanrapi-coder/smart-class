-- ---------- Row Level Security ----------
-- Anon / publik TIDAK bisa mengakses apa pun. Aplikasi ini dipakai
-- dosen tunggal/pemilik: semua user login (authenticated) boleh semua
-- operasi pada tabel akademik. Khusus profiles: membaca boleh semua
-- user login, menulis hanya baris miliknya sendiri.

alter table public.dosen enable row level security;
alter table public.tahun_akademik enable row level security;
alter table public.mata_kuliah enable row level security;
alter table public.kelas enable row level security;
alter table public.mahasiswa enable row level security;
alter table public.anggota_kelas enable row level security;
alter table public.pertemuan enable row level security;
alter table public.absensi enable row level security;
alter table public.komponen_nilai enable row level security;
alter table public.nilai enable row level security;
alter table public.materi enable row level security;
alter table public.tugas enable row level security;
alter table public.pengumpulan_tugas enable row level security;
alter table public.pengaturan enable row level security;
alter table public.profiles enable row level security;

do $$
declare t text; op text;
begin
  foreach t in array array[
    'dosen','tahun_akademik','mata_kuliah','kelas','mahasiswa',
    'anggota_kelas','pertemuan','absensi','komponen_nilai','nilai',
    'materi','tugas','pengumpulan_tugas','pengaturan'
  ] loop
    foreach op in array array['select','insert','update','delete'] loop
      execute format('drop policy if exists %I on public.%I', 'authenticated ' || op, t);
    end loop;
    execute format(
      'create policy "authenticated select" on public.%I
         for select to authenticated using (true)', t);
    execute format(
      'create policy "authenticated insert" on public.%I
         for insert to authenticated with check (true)', t);
    execute format(
      'create policy "authenticated update" on public.%I
         for update to authenticated using (true) with check (true)', t);
    execute format(
      'create policy "authenticated delete" on public.%I
         for delete to authenticated using (true)', t);
  end loop;
end $$;

-- Kebijakan khusus profiles: semua user login boleh melihat foto,
-- tetapi menulis hanya baris miliknya sendiri.
drop policy if exists "profiles read" on public.profiles;
create policy "profiles read" on public.profiles
  for select to authenticated using (true);
drop policy if exists "profiles insert own" on public.profiles;
create policy "profiles insert own" on public.profiles
  for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "profiles update own" on public.profiles;
create policy "profiles update own" on public.profiles
  for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "profiles delete own" on public.profiles;
create policy "profiles delete own" on public.profiles
  for delete to authenticated using (user_id = auth.uid());

