-- ---------- Row Level Security (v8: multi-akun dua peran) ----------
-- Anon / publik TIDAK bisa mengakses apa pun.
-- Dosen (authenticated): CRUD hanya baris miliknya (owner_id).
-- Admin (profiles.role = 'admin'): SELECT semua data untuk
-- monitoring + mengelola profiles; TIDAK bisa menulis tabel kerja
-- dosen. Fungsi publik halaman mahasiswa berjalan SECURITY DEFINER
-- sehingga tidak terpengaruh RLS ini.

-- Fungsi pembantu peran (SECURITY DEFINER, membaca profiles).
create or replace function public.my_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select p.role from public.profiles p where p.user_id = auth.uid()),
    nullif(auth.jwt() -> 'app_metadata' ->> 'role', ''),
    'dosen'
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.my_role() = 'admin';
$$;

-- Trigger pengisi owner_id otomatis dari auth.uid().
create or replace function public.assign_owner_id()
returns trigger
language plpgsql
as $$
begin
  if new.owner_id is null then
    new.owner_id := auth.uid();
  end if;
  return new;
end;
$$;

-- Penjaga profiles: non-admin tidak bisa mengubah role/dosen_id/aktif.
create or replace function public.profiles_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(auth.role(), '') = 'service_role' then
    return new;
  end if;
  if not public.is_admin() then
    new.role := old.role;
    new.dosen_id := old.dosen_id;
    new.aktif := old.aktif;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_profiles_guard on public.profiles;
create trigger trg_profiles_guard
  before update on public.profiles
  for each row execute function public.profiles_guard();

