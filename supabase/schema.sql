-- ---------- Tabel ----------

create table if not exists public.dosen (
  id bigint generated by default as identity primary key,
  nidn text unique,
  nama text not null,
  email text,
  no_hp text,
  prodi text,
  fakultas text,
  foto text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tahun_akademik (
  id bigint generated by default as identity primary key,
  tahun text not null,
  semester text not null check (semester in ('Ganjil','Genap','Pendek')),
  aktif integer not null default 0,
  created_at timestamptz not null default now(),
  unique (tahun, semester)
);

create table if not exists public.mata_kuliah (
  id bigint generated by default as identity primary key,
  kode text unique,
  nama text not null,
  sks integer default 3,
  semester integer,
  prodi text,
  deskripsi text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.kelas (
  id bigint generated by default as identity primary key,
  kode_kelas text not null,
  mata_kuliah_id bigint not null references public.mata_kuliah(id) on delete restrict,
  dosen_id bigint not null references public.dosen(id) on delete restrict,
  tahun_akademik_id bigint not null references public.tahun_akademik(id) on delete restrict,
  ruang text,
  hari text,
  jam_mulai text,
  jam_selesai text,
  kapasitas integer default 40,
  status text default 'Aktif' check (status in ('Aktif','Selesai','Nonaktif')),
  deskripsi text,
  token_bagikan text,
  bagikan_aktif boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (kode_kelas, mata_kuliah_id, dosen_id, tahun_akademik_id)
);

create unique index if not exists kelas_token_bagikan_unik
  on public.kelas (token_bagikan);

create table if not exists public.mahasiswa (
  id bigint generated by default as identity primary key,
  nim text not null unique,
  nama text not null,
  jenis_kelamin text check (jenis_kelamin in ('L','P')),
  prodi text,
  angkatan integer,
  email text,
  no_hp text,
  foto text,
  status text default 'Aktif' check (status in ('Aktif','Cuti','Lulus','Nonaktif')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.anggota_kelas (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.kelas(id) on delete cascade,
  mahasiswa_id bigint not null references public.mahasiswa(id) on delete cascade,
  status text default 'Aktif' check (status in ('Aktif','Nonaktif','Lulus','Drop')),
  nomor_absen integer,
  created_at timestamptz not null default now(),
  unique (kelas_id, mahasiswa_id)
);

create table if not exists public.pertemuan (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.kelas(id) on delete cascade,
  pertemuan_ke integer not null,
  tanggal date not null,
  jam_mulai text,
  jam_selesai text,
  topik text,
  catatan text,
  status text default 'Terjadwal' check (status in ('Terjadwal','Berlangsung','Selesai','Dibatalkan')),
  created_at timestamptz not null default now(),
  unique (kelas_id, pertemuan_ke)
);

create table if not exists public.absensi (
  id bigint generated by default as identity primary key,
  pertemuan_id bigint not null references public.pertemuan(id) on delete cascade,
  mahasiswa_id bigint not null references public.mahasiswa(id) on delete cascade,
  status text not null check (status in ('Hadir','Izin','Sakit','Alpha','Terlambat')),
  waktu_absen text,
  keterangan text,
  created_at timestamptz not null default now(),
  unique (pertemuan_id, mahasiswa_id)
);

create table if not exists public.komponen_nilai (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.kelas(id) on delete cascade,
  nama text not null,
  bobot numeric default 0,
  created_at timestamptz not null default now(),
  unique (kelas_id, nama)
);

create table if not exists public.nilai (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.kelas(id) on delete cascade,
  mahasiswa_id bigint not null references public.mahasiswa(id) on delete cascade,
  komponen_nilai_id bigint not null references public.komponen_nilai(id) on delete cascade,
  nilai_angka numeric default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (kelas_id, mahasiswa_id, komponen_nilai_id)
);

-- Lampiran desktop (file_path lokal) diganti tautan file_url + file_name
-- (mis. Google Drive) pada versi online.
create table if not exists public.materi (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.kelas(id) on delete cascade,
  pertemuan_id bigint references public.pertemuan(id) on delete set null,
  judul text not null,
  deskripsi text,
  file_url text,
  file_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.tugas (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.kelas(id) on delete cascade,
  judul text not null,
  deskripsi text,
  deadline text,
  bobot numeric default 0,
  file_url text,
  file_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.pengumpulan_tugas (
  id bigint generated by default as identity primary key,
  tugas_id bigint not null references public.tugas(id) on delete cascade,
  mahasiswa_id bigint not null references public.mahasiswa(id) on delete cascade,
  waktu_kumpul text,
  file_url text,
  file_name text,
  nilai numeric,
  status text default 'Belum Dinilai' check (status in ('Belum Dinilai','Sudah Dinilai','Terlambat')),
  catatan text,
  created_at timestamptz not null default now(),
  unique (tugas_id, mahasiswa_id)
);

create table if not exists public.pengaturan (
  kunci text primary key,
  nilai text
);

